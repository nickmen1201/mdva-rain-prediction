package ti.mdva.usecases;

import ti.mdva.repositories.ViajeRepositoryImpl;
import org.springframework.stereotype.Service;
import ti.mdva.jooq.tables.pojos.Viajes;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

/* UseCase para las operaciones de Viaje

TODO: Revisar posibilidad de cambiar manejo de barrios a ubicaciones específicas usando API PLACES de Google Maps */

@Service
public class ViajeUseCase {

    private final ViajeRepositoryImpl viajeRepository;

    public ViajeUseCase(ViajeRepositoryImpl viajeRepository) {
        this.viajeRepository = viajeRepository;
    }

    /**
     * Initiates a new viaje.
     * - idViaje is auto-generated by the DB, so it must not be set.
     * - horaInicio defaults to now if not provided.
     * - finalizado defaults to false.
     * - horaFin and userRating are not set at creation time.
     *
     * @param idUsuario        ID of the user requesting the trip
     * @param idVehiculo       ID of the assigned vehicle (nullable)
     * @param idBarrioOrigen   origin neighborhood
     * @param idBarrioDestino  destination neighborhood
     * @param tiempoEstimadoMin estimated duration in minutes
     * @param precipitacionMm  rainfall in mm (defaults to 0 if null)
     * @return the persisted Viaje with its generated idViaje
     */
    public Viajes crearViaje(
            Integer idUsuario,
            String idVehiculo,
            String idBarrioOrigen,
            String idBarrioDestino,
            Short tiempoEstimadoMin, // TODO: Consumir desde modelo de ML, por el momento, se recibe como parámetro
            Short precipitacionMm    // TODO: Consumir desde SIATA, por el momento, se recibe como parámetro
    ) {
        // Origen y destino no pueden ser el mismo
        if (idBarrioOrigen.equalsIgnoreCase(idBarrioDestino)) {
            throw new IllegalArgumentException(
                "El barrio de origen y destino no pueden ser el mismo."
            );
        }

        // El tiempo estimado debe ser positivo
        if (tiempoEstimadoMin <= 0) {
            throw new IllegalArgumentException(
                "El tiempo estimado debe ser mayor a 0 minutos."
            );
        }

        Viajes nuevoViaje = new Viajes();
        nuevoViaje.setIdUsuario(idUsuario);
        nuevoViaje.setIdVehiculo(idVehiculo);
        nuevoViaje.setIdBarrioOrigen(idBarrioOrigen);
        nuevoViaje.setIdBarrioDestino(idBarrioDestino);
        nuevoViaje.setTiempoEstimadoMin(tiempoEstimadoMin);
        nuevoViaje.setHoraInicio(OffsetDateTime.now());
        nuevoViaje.setPrecipitacionMm(precipitacionMm != null ? precipitacionMm : (short) 0);
        nuevoViaje.setFinalizado(false);
        
        /* TODO: horaFin y userRating se dejan como null al crear el viaje,
        pero se necesita un manejo especial a la hora de finalizar el viaje para actualizarlos en caso de que sea necesario
        */

        return viajeRepository.save(nuevoViaje);
    }

    // -------------------------------------------------------------------------
    // FinalizarViaje
    // -------------------------------------------------------------------------

    /**
     * Finalizes an existing viaje.
     * - Sets horaFin to now.
     * - Sets finalizado to true.
     * - Cannot finalize a viaje that is already finished.
     *
     * @param idViaje the ID of the trip to finalize
     * @return the updated Viaje
     */
    public Viajes finalizarViaje(Integer idViaje) {
        Viajes viaje = viajeRepository.findById(idViaje)
                .orElseThrow(() -> new IllegalArgumentException(
                    "No se encontró un viaje con id: " + idViaje
                ));

        // No se puede finalizar un viaje que ya ha sido finalizado
        if (Boolean.TRUE.equals(viaje.getFinalizado())) {
            throw new IllegalStateException(
                "El viaje con id " + idViaje + " ya fue finalizado."
            );
        }

        viaje.setFinalizado(true);
        viaje.setHoraFin(OffsetDateTime.now());

        return viajeRepository.save(viaje);
    }
}