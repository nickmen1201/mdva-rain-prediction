-- =============================================================================
-- V1__initial_schema.sql
-- Esquema inicial de la base de datos MDVA.
-- Usa IF NOT EXISTS para ser idempotente en bases de datos locales ya existentes.
-- =============================================================================

-- ----------------------------------------------------------------------------
-- Tablas geográficas (sin dependencias externas)
-- ----------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS municipios (
    id_municipio VARCHAR(20)  NOT NULL,
    nombre       VARCHAR(255) NOT NULL,
    CONSTRAINT municipios_pkey PRIMARY KEY (id_municipio)
);

CREATE TABLE IF NOT EXISTS comunas (
    id_comuna    VARCHAR(20)  NOT NULL,
    nombre       VARCHAR(255) NOT NULL,
    id_municipio VARCHAR(20)  NOT NULL,
    CONSTRAINT comunas_pkey PRIMARY KEY (id_comuna),
    CONSTRAINT comunas_id_municipio_fkey FOREIGN KEY (id_municipio) REFERENCES municipios (id_municipio)
);
CREATE INDEX IF NOT EXISTS idx_comunas_municipio ON comunas (id_municipio);

CREATE TABLE IF NOT EXISTS barrios (
    id_barrio VARCHAR(20)  NOT NULL,
    nombre    VARCHAR(255) NOT NULL,
    id_comuna VARCHAR(20)  NOT NULL,
    CONSTRAINT barrios_pkey PRIMARY KEY (id_barrio),
    CONSTRAINT barrios_id_comuna_fkey FOREIGN KEY (id_comuna) REFERENCES comunas (id_comuna)
);
CREATE INDEX IF NOT EXISTS idx_barrios_comuna ON barrios (id_comuna);

-- ----------------------------------------------------------------------------
-- Tablas de catálogo de vehículos
-- ----------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS tipos_motor (
    id_motorizacion SMALLINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre          VARCHAR(100) NOT NULL,
    CONSTRAINT tipos_motor_pkey      PRIMARY KEY (id_motorizacion),
    CONSTRAINT tipos_motor_nombre_key UNIQUE      (nombre)
);

CREATE TABLE IF NOT EXISTS tipos_vehiculo (
    id_tipo_vehiculo SMALLINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre           VARCHAR(100) NOT NULL,
    vulnerabilidad   SMALLINT     NOT NULL,
    CONSTRAINT tipos_vehiculo_pkey             PRIMARY KEY (id_tipo_vehiculo),
    CONSTRAINT tipos_vehiculo_nombre_key        UNIQUE      (nombre),
    CONSTRAINT tipos_vehiculo_vulnerabilidad_check CHECK (vulnerabilidad >= 0 AND vulnerabilidad <= 100)
);

-- ----------------------------------------------------------------------------
-- Usuarios
-- ----------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS usuarios (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre           VARCHAR(120) NOT NULL,
    username         VARCHAR(60)  NOT NULL,
    email            VARCHAR(255) NOT NULL,
    fecha_nacimiento DATE,
    creado_en        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    authhash         VARCHAR(255),
    id_barrio        VARCHAR(20),
    CONSTRAINT usuarios_pkey         PRIMARY KEY (id),
    CONSTRAINT usuarios_username_key  UNIQUE      (username),
    CONSTRAINT usuarios_email_key     UNIQUE      (email),
    CONSTRAINT usuarios_id_barrio_fkey FOREIGN KEY (id_barrio) REFERENCES barrios (id_barrio)
);
CREATE INDEX IF NOT EXISTS idx_usuarios_barrio ON usuarios (id_barrio);

-- ----------------------------------------------------------------------------
-- Vehículos
-- ----------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS vehiculos (
    placa            VARCHAR(10)  NOT NULL,
    id_usuario       INTEGER      NOT NULL,
    id_tipo_vehiculo SMALLINT     NOT NULL,
    id_motorizacion  SMALLINT     NOT NULL,
    marca            VARCHAR(100) NOT NULL,
    modelo           VARCHAR(100) NOT NULL,
    ano              SMALLINT     NOT NULL,
    CONSTRAINT vehiculos_pkey                    PRIMARY KEY (placa),
    CONSTRAINT vehiculos_id_usuario_fkey          FOREIGN KEY (id_usuario)       REFERENCES usuarios      (id),
    CONSTRAINT vehiculos_id_tipo_vehiculo_fkey    FOREIGN KEY (id_tipo_vehiculo)  REFERENCES tipos_vehiculo (id_tipo_vehiculo),
    CONSTRAINT vehiculos_id_motorizacion_fkey     FOREIGN KEY (id_motorizacion)   REFERENCES tipos_motor   (id_motorizacion),
    CONSTRAINT vehiculos_ano_check                CHECK (ano >= 1900 AND ano <= EXTRACT(year FROM CURRENT_DATE) + 1)
);
CREATE INDEX IF NOT EXISTS idx_vehiculos_usuario ON vehiculos (id_usuario);

-- ----------------------------------------------------------------------------
-- Viajes (esquema original, antes de la migración V2)
-- Las columnas id_barrio_origen / id_barrio_destino serán eliminadas en V3.
-- Las columnas de coordenadas y distancia serán añadidas en V2.
-- ----------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS viajes (
    id_viaje            INTEGER     GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_usuario          INTEGER     NOT NULL,
    id_vehiculo         VARCHAR(10),
    id_barrio_origen    VARCHAR(20),
    id_barrio_destino   VARCHAR(20),
    tiempo_estimado_min SMALLINT    NOT NULL,
    hora_inicio         TIMESTAMPTZ NOT NULL,
    hora_fin            TIMESTAMPTZ,
    precipitacion_mm    SMALLINT    DEFAULT 0,
    finalizado          BOOLEAN     NOT NULL DEFAULT false,
    user_rating         SMALLINT,
    CONSTRAINT viajes_pkey               PRIMARY KEY (id_viaje),
    CONSTRAINT viajes_id_usuario_fkey     FOREIGN KEY (id_usuario)  REFERENCES usuarios  (id),
    CONSTRAINT viajes_id_vehiculo_fkey    FOREIGN KEY (id_vehiculo) REFERENCES vehiculos (placa),
    CONSTRAINT viajes_user_rating_check   CHECK (user_rating >= 1 AND user_rating <= 5)
);
CREATE INDEX IF NOT EXISTS idx_viajes_fecha   ON viajes (hora_inicio);
CREATE INDEX IF NOT EXISTS idx_viajes_usuario ON viajes (id_usuario);
