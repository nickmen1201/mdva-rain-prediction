package ti.mdva.usecases;

import org.springframework.security.crypto.bcrypt.BCryptPasswordEncoder;
import org.springframework.stereotype.Service;
import ti.mdva.jooq.tables.pojos.Usuarios;
import ti.mdva.interfaces.IUsuarioRepository;

import java.time.LocalDate;
import java.time.OffsetDateTime;


/*
    UseCase para las operaciones de usuario
*/
@Service
public class UsuarioUseCase {

    private final IUsuarioRepository usuarioRepository;
    private final BCryptPasswordEncoder passwordEncoder;

    public UsuarioUseCase(IUsuarioRepository usuarioRepository) {
        this.usuarioRepository = usuarioRepository;
        this.passwordEncoder = new BCryptPasswordEncoder();
    }

    // -------------------------------------------------------------------------
    // RegistrarUsuario
    // -------------------------------------------------------------------------

    /**
     * Registers a new usuario.
     * - id is auto-generated by the DB.
     * - creadoEn defaults to now.
     * - authhash is BCrypt-hashed from the raw password before persistence.
     * - username and email must be unique.
     *
     * @param nombre          full name
     * @param username        unique username
     * @param email           unique email address
     * @param rawPassword     plain-text password — will be hashed before saving
     * @param fechaNacimiento optional date of birth
     * @param idBarrio        optional neighborhood ID
     * @return the persisted Usuario with its generated id
     */
    public Usuarios registrarUsuario(
            String nombre,
            String username,
            String email,
            String rawPassword,
            LocalDate fechaNacimiento,
            String idBarrio
    ) {
        
        // No aceptamos nombres de usuario idénticos
        if (usuarioRepository.existsByUsername(username)) {
            throw new IllegalArgumentException(
                "El username '" + username + "' ya está en uso."
            );
        }

        // No aceptamos emails idénticos
        if (usuarioRepository.existsByEmail(email)) {
            throw new IllegalArgumentException(
                "El email '" + email + "' ya está registrado."
            );
        }

        // Hasheamos la contraseña usando BCrypt antes de guardar el usuario
        String authhash = passwordEncoder.encode(rawPassword);

        Usuarios nuevoUsuario = new Usuarios();
        nuevoUsuario.setNombre(nombre);
        nuevoUsuario.setUsername(username);
        nuevoUsuario.setEmail(email);
        nuevoUsuario.setAuthhash(authhash);
        nuevoUsuario.setFechaNacimiento(fechaNacimiento);
        nuevoUsuario.setCreadoEn(OffsetDateTime.now());
        nuevoUsuario.setIdBarrio(idBarrio);
        
        // Recordar que el id es automático, evitamos asignarlo manualmente

        return usuarioRepository.save(nuevoUsuario);
    }
}